// Render a verdict as a terminal report, Markdown (with a badge) or JSON.

const plural = (n, one, many = one + 's') => `${n} ${n === 1 ? one : many}`;

export function badgeUrl(v) {
  const s = v.summary;
  const [label, color] = s.zeroEgress
    ? ['0 egress', 'brightgreen']
    : s.unexpected === 0
      ? [`${s.allowed} allowed, 0 unexpected`, 'green']
      : [`${s.unexpected} unexpected egress`, 'red'];
  const enc = (t) => encodeURIComponent(t.replace(/-/g, '--').replace(/_/g, '__'));
  return `https://img.shields.io/badge/phonehome-${enc(label)}-${color}`;
}

export function headline(v) {
  const s = v.summary;
  if (s.zeroEgress) return '0 egress: no DNS lookups and no outbound connections';
  if (s.unexpected === 0) return `0 unexpected egress (${plural(s.lookups, 'DNS lookup')}, ${plural(s.destinations, 'destination')}, all allowed)`;
  const parts = [];
  if (s.unexpectedLookups) parts.push(plural(s.unexpectedLookups, 'DNS lookup'));
  if (s.unexpectedDestinations) parts.push(plural(s.unexpectedDestinations, 'destination'));
  return `egress detected: ${parts.join(', ')} not on the allowlist`;
}

function table(rows, headers) {
  const all = [headers, ...rows];
  const widths = headers.map((_, i) => Math.max(...all.map((r) => String(r[i]).length)));
  const line = (r) => r.map((c, i) => String(c).padEnd(widths[i])).join('  ').trimEnd();
  return [line(headers), ...rows.map(line)].join('\n');
}

const mark = (allowed) => (allowed ? 'allowed' : 'UNEXPECTED');
const addr = (c) => (c.ip.includes(':') ? `[${c.ip}]:${c.port}` : `${c.ip}:${c.port}`);
const host = (c) => (c.hosts.length ? c.hosts.join(', ') : '-');
const resultOf = (c) => c.outcomes.map((o) => (o === 'EINPROGRESS' ? 'ok' : o)).filter((o, i, a) => a.indexOf(o) === i).join(',') || '-';

export function shellJoin(argv) {
  return argv.map((a) => (/^[\w@%+=:,./-]+$/.test(a) ? a : `'${a.replace(/'/g, `'\\''`)}'`)).join(' ');
}

export function renderText(v, { command, color = false } = {}) {
  const c = (code, t) => (color ? `\x1b[${code}m${t}\x1b[0m` : t);
  const out = [];
  if (command) out.push(`phonehome: traced ${shellJoin(command)}`);
  if (v.stopped) out.push(`phonehome: stopped after ${v.stopped}`);
  const procs = v.processes.length;
  out.push(`phonehome: ${plural(procs, 'process', 'processes')} observed`);
  out.push('');
  if (v.lookups.length) {
    out.push('DNS lookups');
    out.push(table(v.lookups.map((l) => [l.name, l.types.join(','), l.processes.join(', ') || '-', l.count, mark(l.allowed)]), ['name', 'type', 'process', 'count', '']));
    out.push('');
  }
  if (v.connections.length) {
    out.push('Outbound destinations');
    out.push(table(v.connections.map((x) => [host(x), addr(x), x.proto, x.processes.join(', '), x.count, resultOf(x), mark(x.allowed)]), ['host', 'address', 'proto', 'process', 'count', 'result', '']));
    out.push('');
  }
  const meta = v.connections.filter((x) => x.kind === 'metadata');
  if (meta.length) out.push(c('33', `note: contacted a cloud metadata address (${meta.map(addr).join(', ')})`), '');
  if (v.probes.length) {
    out.push(`note: ${plural(v.probes.length, 'UDP socket')} connected without sending data (source-address probes, not counted): ${v.probes.map(addr).join(', ')}`);
    out.push('');
  }
  if (v.local.length) {
    const n = v.local.reduce((a, b) => a + b.count, 0);
    out.push(`local only: ${plural(n, 'loopback connection')} (not egress)`);
    out.push('');
  }
  const s = v.summary;
  const text = headline(v);
  out.push(s.unexpected === 0 ? c('32', `✓ ${text}`) : c('31', `✗ ${text}`));
  return out.join('\n');
}

export function renderMarkdown(v, { command } = {}) {
  const out = [];
  out.push(`![phonehome](${badgeUrl(v)})`);
  out.push('');
  if (command) out.push(`Traced: \`${shellJoin(command)}\``, '');
  out.push(`**${headline(v)}**`, '');
  if (v.lookups.length) {
    out.push('| DNS lookup | type | process | count | |', '|---|---|---|---|---|');
    for (const l of v.lookups) out.push(`| ${l.name} | ${l.types.join(',')} | ${l.processes.join(', ') || '-'} | ${l.count} | ${mark(l.allowed)} |`);
    out.push('');
  }
  if (v.connections.length) {
    out.push('| host | address | proto | process | count | result | |', '|---|---|---|---|---|---|---|');
    for (const x of v.connections) out.push(`| ${host(x)} | ${addr(x)} | ${x.proto} | ${x.processes.join(', ')} | ${x.count} | ${resultOf(x)} | ${mark(x.allowed)} |`);
    out.push('');
  }
  out.push(`<sub>Generated by [phonehome](https://github.com/jatingargiitk/phonehome) on ${v.platform || process.platform} with strace.</sub>`);
  return out.join('\n') + '\n';
}

export function toJson(v, extra = {}) {
  return {
    tool: 'phonehome',
    version: extra.version,
    command: extra.command || null,
    platform: v.platform || process.platform,
    durationMs: extra.durationMs ?? null,
    exitCode: extra.exitCode ?? null,
    stopped: v.stopped || null,
    result: v.summary.unexpected === 0 ? (v.summary.zeroEgress ? 'zero-egress' : 'allowed-only') : 'unexpected-egress',
    badge: badgeUrl(v),
    summary: v.summary,
    lookups: v.lookups,
    connections: v.connections,
    probes: v.probes,
    resolvers: v.resolvers,
    local: v.local,
    processes: v.processes,
  };
}
